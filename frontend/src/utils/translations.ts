export function getTranslations(): Translations {
  try {
    const slug = localStorage.getItem("typerace_lang_slug") ?? undefined;
    const langInfo = getLanguageFromSlug(slug);
    return translations[langInfo.language] || translations[Language.English];
  } catch {}
  return translations[Language.English];
}
