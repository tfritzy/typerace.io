export function getRandomWord(langCode: string, exclude?: Set<string>): string {
  const words = getWordList(langCode);
  if (!exclude || exclude.size >= words.length) {
    return words[Math.floor(Math.random() * words.length)];
  }
  let word: string;
  do {
    word = words[Math.floor(Math.random() * words.length)];
  } while (exclude.has(word));
  return word;
}
